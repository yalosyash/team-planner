/* ============================================================
   core/render.js — единая точка перерисовки.

   Модули не вызывают друг друга напрямую: они сообщают «данные
   изменились», а какие части интерфейса перерисовать — решает
   этот реестр. Так нет циклических импортов.
   ============================================================ */
const renderers = [];

/* Подписать часть интерфейса на перерисовку (порядок важен: шапка,
   вкладки, доска) */
export function onRender(fn) {
  renderers.push(fn);
}

export function render() {
  renderers.forEach((fn) => fn());
}
